// OBS WebSocket v5 client (one-click sync inside OBS Dock)
let ws=null,wsReady=false,reqId=1;
async function sha256b64(str){
  const buf=await crypto.subtle.digest('SHA-256',new TextEncoder().encode(str));
  return btoa(String.fromCharCode(...new Uint8Array(buf)));
}
function setWsUi(ok,msg){
  wsReady=ok;
  document.getElementById('wsDot').className='dot '+(ok?'ok':'err');
  document.getElementById('wsStatus').textContent=msg;
}
function connectWs(){
  if(ws){try{ws.close()}catch(e){}}
  setWsUi(false,'در حال اتصال...');
  try{ws=new WebSocket(WS_URL)}catch(e){setWsUi(false,'خطای آدرس WS');return}
  ws.onmessage=async ev=>{
    try{
      const m=JSON.parse(ev.data);
      if(m.op===0){
        let auth;
        if(m.d&&m.d.authentication){
          const sec=await sha256b64(WS_PASS+m.d.authentication.salt);
          auth=await sha256b64(sec+m.d.authentication.challenge);
        }
        ws.send(JSON.stringify({op:1,d:{rpcVersion:1,...(auth?{authentication:auth}:{})}}));
      }else if(m.op===2){
        setWsUi(true,'متصل به OBS');
      }
    }catch(e){}
  };
  ws.onerror=()=>setWsUi(false,'OBS قطع (پورت 4455)');
  ws.onclose=()=>{if(wsReady)setWsUi(false,'OBS قطع شد')};
}
