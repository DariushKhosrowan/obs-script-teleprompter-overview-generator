function escapeLuaString(value: string): string {
  return value
    .replace(/\\/g, '\\\\')
    .replace(/"/g, '\\"')
    .replace(/\r?\n/g, '\\n');
}

export function generateStepsDataLua(steps: StudioStep[]): string {
  const lines = steps.map((s) => {
    const fields: string[] = [
      `act=${s.act}`,
      `layout="${s.layoutKey}"`,
      `slide=${s.slide}`,
      `text="${escapeLuaString(s.text)}"`,
    ];
    if (s.motion && s.motion !== 'auto') {
      fields.push(`motion="${s.motion}"`);
    }
    if (s.zoom) {
      fields.push(`zoom={s=${s.zoom.s}, x=${s.zoom.x}, y=${s.zoom.y}}`);
    }
    return `  {${fields.join(', ')}},`;
  });

  return `-- Generated by Hark Studio\nreturn {\n${lines.join('\n')}\n}\n`;
}

