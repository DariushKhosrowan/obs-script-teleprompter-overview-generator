import test from 'node:test';
import assert from 'node:assert/strict';
import { DEFAULT_STEPS } from '../data/defaultSteps';
import {
  computeActSummaries,
  computeTotalRecordedSec,
  formatMMSS,
  getFirstStepIndexOfAct,
  getNextStepIndex,
  getPrevStepIndex,
  toPersianDigits,
} from './persian';
import {
  generateInstallerScript,
  generateLuaV8,
  generatePrompterHtml,
  generateStepsDataLua,
} from './obsGenerators';
import type { ObsSettings } from '../types/studio';

const SAMPLE_SETTINGS: ObsSettings = {
  wsUrl: 'ws://127.0.0.1:4455',
  wsPassword: 'secret',
  integrationMode: 'dock_ws',
  osTarget: 'linux',
  pollIntervalMs: 150,
  clickTextToAdvance: true,
  autoStudioPreviewSync: true,
  fontSizePx: 42,
  mirror: false,
  autoScroll: false,
  scrollSpeed: 1.2,
};

test('DEFAULT_STEPS contains all 38 steps with valid layout keys', () => {
  assert.equal(DEFAULT_STEPS.length, 38);
  assert.equal(DEFAULT_STEPS[0].layoutKey, 'SLIDE');
  assert.equal(DEFAULT_STEPS[1].layoutKey, 'SCAM');
  assert.equal(DEFAULT_STEPS[37].layoutKey, 'CAM');
});

test('Persian digit formatting and MM:SS timecodes work accurately', () => {
  assert.equal(toPersianDigits(123), '۱۲۳');
  assert.equal(formatMMSS(0), '۰۰:۰۰');
  assert.equal(formatMMSS(85), '۰۱:۲۵');
});

test('Step navigation clamps cleanly at boundaries and jumps to act start', () => {
  assert.equal(getNextStepIndex(0, DEFAULT_STEPS), 1);
  assert.equal(getNextStepIndex(37, DEFAULT_STEPS), 37);
  assert.equal(getPrevStepIndex(0, DEFAULT_STEPS), 0);
  assert.equal(getPrevStepIndex(5, DEFAULT_STEPS), 4);
  assert.equal(getFirstStepIndexOfAct(2, DEFAULT_STEPS), 8);
  assert.equal(getFirstStepIndexOfAct(6, DEFAULT_STEPS), 33);
});

test('Act summaries aggregate takes and durations correctly', () => {
  const summaries = computeActSummaries(DEFAULT_STEPS, [
    { act: 1, take: 1, start: 100, stop: 165 },
    { act: 1, take: 2, start: 200, stop: 272 },
    { act: 2, take: 1, start: 300, stop: 390 },
  ]);
  assert.equal(summaries.length, 6);
  assert.equal(summaries[0].takes.length, 2);
  assert.equal(summaries[0].latestDurationSec, 72);
  assert.equal(computeTotalRecordedSec([
    { act: 1, take: 1, start: 100, stop: 165 },
    { act: 1, take: 2, start: 200, stop: 272 },
    { act: 2, take: 1, start: 300, stop: 390 },
  ]), 162);
});

test('generateStepsDataLua escapes quotes and writes valid Lua table entries', () => {
  const lua = generateStepsDataLua(DEFAULT_STEPS.slice(0, 2));
  assert.match(lua, /^-- Generated by Hark Studio\nreturn \{/);
  assert.match(lua, /act=1, layout="SLIDE", slide=1/);
  assert.match(lua, /act=1, layout="SCAM", slide=1/);
});

test('generateLuaV8 includes native OBS text fallback and Studio Mode preview sync', () => {
  const lua = generateLuaV8(DEFAULT_STEPS, SAMPLE_SETTINGS);
  assert.match(lua, /text_ft2_source_v2/);
  assert.match(lua, /update_native_prompter_text/);
  assert.match(lua, /sync_studio_preview/);
  assert.match(lua, /obs_frontend_set_current_preview_scene/);

  const winLua = generateLuaV8(DEFAULT_STEPS, {
    ...SAMPLE_SETTINGS,
    osTarget: 'windows',
  });
  assert.match(winLua, /text_gdiplus_v2/);
});

test('generatePrompterHtml embeds steps JSON, WebSocket trigger, and fast state polling', () => {
  const html = generatePrompterHtml(DEFAULT_STEPS, SAMPLE_SETTINGS);
  assert.match(html, /TriggerHotkeyByName/);
  assert.match(html, /hs_next/);
  assert.match(html, /POLL_MS=150/);
  assert.match(html, /فرض کن گوشیت زنگ می‌خوره/);
});

test('generateInstallerScript bundles all three files with backup directory logic', () => {
  const sh = generateInstallerScript(DEFAULT_STEPS, SAMPLE_SETTINGS);
  assert.match(sh, /^#!\/usr\/bin\/env bash/);
  assert.match(sh, /hark_studio_v8\.lua/);
  assert.match(sh, /steps_data\.lua/);
  assert.match(sh, /prompter\.html/);
  assert.match(sh, /backup_v7_/);
});

test('generated Lua script contains no unfinished single-line quoted strings', () => {
  const lua = generateLuaV8(DEFAULT_STEPS, SAMPLE_SETTINGS);
  assert.match(lua, /g:write\("return \{\\n"\)/);
  assert.match(lua, /g:write\("\}\\n"\)/);
  assert.doesNotMatch(lua, /g:write\("return \{\n/);
  assert.doesNotMatch(lua, /g:write\("\}\n/);
});
